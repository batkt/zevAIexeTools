<#
.SYNOPSIS
    Quick Configuration Tool for Zev Detector
.DESCRIPTION
    Generates a production config.toml tailored to the current machine.
    Detects local Dahua services, open ports, and log files automatically.
#>

[CmdletBinding()]
param(
    [string]$ServerUrl = "https://admin.zevtabs.mn/api",
    [string]$Token = "",
    [string]$AgentName = $env:COMPUTERNAME,
    [string]$BaiguullagaId = "",
    [string]$BarilgaId = "",
    [string]$OutputPath = "config.toml"
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "         Zev Detector — Machine Auto-Configuration        " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# Detect local services
$HasDahuaSvc = $null -ne (Get-Service -Name "DahuaParkingService" -ErrorAction SilentlyContinue)
Write-Host "Detected Host Name        : $AgentName" -ForegroundColor Yellow
Write-Host "Dahua Service Detected    : $(if ($HasDahuaSvc) {'YES (DahuaParkingService)'} else {'NO'})" -ForegroundColor $(if ($HasDahuaSvc) {'Green'} else {'DarkGray'})

# Detect common Dahua log paths
$PossibleLogPaths = @(
    "D:\zevtabs\dahuarust\dahuaExeRust\target\release\service.log",
    "C:\Program Files\DahuaParkingService\service.log",
    "D:\zevtabs\dahuarust\service.log"
)
$FoundLogPath = $PossibleLogPaths | Where-Object { Test-Path $_ } | Select-Object -First 1

$ConfigContent = @"
# Generated by Zev Detector configure script on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')

[server]
url                = "$ServerUrl"
token              = "$Token"
timeout_secs       = 20
retry_count        = 3
batch_size         = 50
send_interval_secs = 30
queue_max          = 5000

[agent]
name                    = "$AgentName"
baiguullagiinId         = "$BaiguullagaId"
baiguullagiinNer        = ""
barilgiinId             = "$BarilgaId"
heartbeat_interval_secs = 60

[eventlog]
enabled            = true
poll_interval_secs = 60
channels = [
  "System",
  "Application",
]
max_level        = 3
providers        = []
ignore_event_ids = [10016]
ignore_contains  = []
max_per_poll     = 200

"@

if ($HasDahuaSvc) {
$ConfigContent += @"
[[services]]
name                  = "DahuaParkingService"
label                 = "Dahua Parking (dahuarust)"
must_run              = true
auto_restart          = true
max_restarts_per_hour = 3
restart_grace_secs    = 45

"@
} else {
$ConfigContent += @"
# No services configured for auto-restart on this machine
# [[services]]
# name         = "ServiceName"
# label        = "Service Label"
# must_run     = true
# auto_restart = true

"@
}

$LogTarget = if ($FoundLogPath) { $FoundLogPath } else { 'D:\zevtabs\dahuarust\dahuaExeRust\target\release\service.log' }

$ConfigContent += @"
[logs]
enabled            = true
poll_interval_secs = 15

[[logs.files]]
path          = '$LogTarget'
system        = "dahuarust"
modul         = "dahua-service"
context_lines = 8

[timesync]
enabled            = true
poll_interval_secs = 900
max_drift_secs     = 30
auto_resync        = true

[cleanup]
enabled              = true
weekday              = 0
hour                 = 3
min_age_days         = 7
disk_trigger_percent = 92
log_max_mb           = 32

[netqual]
enabled            = true
poll_interval_secs = 300
ping_host          = ""
ping_count         = 10
score_threshold    = 70

[[ports]]
port  = 37777
label = "Dahua SDK"

[[ports]]
port  = 5000
label = "Parking service"

[update]
mode                 = "ask"
check_interval_hours = 6
github_repo          = ""
github_token         = ""
window               = ""

[health]
enabled            = true
poll_interval_secs = 60
cpu_threshold      = 90
mem_threshold      = 90
disk_threshold     = 90

[[health.http]]
name                   = "dahua api"
url                    = "http://127.0.0.1:5000/api/health"
expect                 = "OK"
timeout_secs           = 5
system                 = "dahuarust"
service                = "DahuaParkingService"
restart_after_failures = 3
"@

$ConfigContent | Set-Content -Path $OutputPath -Encoding UTF8
Write-Host "✓ Configuration saved to: $OutputPath" -ForegroundColor Green

# Verify with zev-detector test if exe is available
$DetectorExe = Join-Path (Split-Path -Parent $ScriptDir) "target\release\zev-detector.exe"
if (Test-Path $DetectorExe) {
    Write-Host "`nRunning validation pass with $DetectorExe..." -ForegroundColor Yellow
    & $DetectorExe test
}
Write-Host "`nConfiguration complete!" -ForegroundColor Cyan
